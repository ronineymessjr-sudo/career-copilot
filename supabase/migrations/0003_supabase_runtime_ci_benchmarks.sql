-- Drop earlier permissive/legacy policies when reapplying this migration in preview.
do $$
declare
  table_name text;
  policy_name text;
begin
  foreach table_name in array array[
    'profiles','companies','jobs','job_evaluations','career_evidence','resume_versions',
    'application_packages','applications','interviews','offers','source_snapshots',
    'model_runs','delivery_runs','model_benchmark_runs'
  ] loop
    for policy_name in
      select pol.polname
      from pg_policy pol
      join pg_class cls on cls.oid = pol.polrelid
      join pg_namespace ns on ns.oid = cls.relnamespace
      where ns.nspname = 'public' and cls.relname = table_name
    loop
      execute format('drop policy if exists %I on public.%I', policy_name, table_name);
    end loop;
  end loop;
end $$;

