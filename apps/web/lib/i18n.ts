export type MessageKey = keyof typeof messages.zh;

export function message(locale: Locale, key: MessageKey): string {
  return messages[locale][key] ?? messages.zh[key];
}

export function interpolate(value: string, params: Record<string, string | number>): string {
  return value.replace(/\{(\w+)\}/g, (_, key: string) => String(params[key] ?? `{${key}}`));
}

export function resolveLocale(value: string | null | undefined): Locale {
  return String(value ?? "").toLowerCase().startsWith("en") ? "en" : "zh";
}
