export function normalized(value) {
  return String(value ?? "").toLowerCase().replace(/[^\p{L}\p{N}+#.]+/gu, " ").replace(/\s+/g, " ").trim();
}

export function matchAlias(text, alias) {
  const term = String(alias ?? "").toLowerCase().trim();
  if (!term) return false;
  if (/^[\p{L}]+$/u.test(term) && /^[a-z]+$/i.test(term)) {
    const escaped = term.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    return new RegExp(`(^|[^a-z0-9])${escaped}([^a-z0-9]|$)`, "i").test(text);
  }
  if (/^[a-z0-9][a-z0-9 .+_-]*$/i.test(term)) {
    const escaped = term.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    return new RegExp(`(^|[^a-z0-9])${escaped}([^a-z0-9]|$)`, "i").test(text);
  }
  return text.includes(term);
}

export function intersect(left, right) {
  return [...left].filter((item) => right.has(item));
}

export function tokenize(value) {
  const text = normalized(value);
  const tokens = new Set(text.split(" ").filter((item) => item.length > 1));
  for (const [canonical, aliases] of Object.entries(SKILLS)) {
    if (aliases.some((alias) => matchAlias(text, alias))) tokens.add(canonical);
  }
  return tokens;
}

export function extractJobSkills(job) {
  const text = normalized(`${job?.title ?? ""} ${job?.description ?? ""} ${job?.requirements ?? ""}`);
  return Object.entries(SKILLS)
    .filter(([canonical, aliases]) => aliases.some((alias) => {
      if (canonical !== "payroll" || !["薪酬", "薪资", "福利"].includes(alias)) return matchAlias(text, alias);
      // Compensation ranges in an arbitrary JD are not payroll experience.
      // Keep payroll as a skill only when the surrounding text is explicitly HR/payroll work.
      const hrContext = /人力资源|人事|招聘|hr\b|员工关系|薪酬管理|薪资管理|工资核算|薪资核算|福利管理|payroll/i.test(text);
      return hrContext && matchAlias(text, alias);
    }))
    .map(([canonical]) => canonical);
}

export function canonicalSkills(terms = []) {
  const result = new Set();
  for (const term of terms) {
    const raw = normalized(term);
    let found = false;
    for (const [canonical, aliases] of Object.entries(SKILLS)) {
      if (normalized(canonical) === raw || aliases.some((alias) => normalized(alias) === raw)) { result.add(canonical); found = true; break; }
    }
    if (!found) result.add(raw);
  }
  return result;
}
